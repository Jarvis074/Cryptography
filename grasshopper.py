S_box_inv = [0] * 256
for i,v in enumerate(S_box):
    S_box_inv[v] = i

L_vec = [148, 32, 133, 16, 194, 192, 1, 251, 1, 192, 194, 16, 133, 32, 148, 1]

def gf_mul(a, b):
    res = 0

    for _ in range(8):
        if b & 1:
            res ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0xC3
        b >>= 1

    return res

def r_operation(state):
    a15 = state[-1]
    new0 = a15

    for i in range(15):
        new0 ^= gf_mul(state[i], L_vec[i])

    for i in range(15,0,-1):
        state[i] = state[i - 1]

    state[0] = new0

def r_inv_operation(state):
    new_last = state[0]

    for i in range(15):
        new_last ^= gf_mul(state[i + 1], L_vec[i])

    for i in range(0,15):
        state[i] = state[i+1]

    state[15] = new_last

def l_operation(state):
    s = list(state)

    for _ in range(16):
        r_operation(s)

    return bytes(s)

def l_inv_operation(state):
    s = list(state)

    for _ in range(16):
        r_inv_operation(s)

    return bytes(s)

def s_operation(state):
    return bytes(S_box[b] for b in state)

def s_inv_operation(state):
    return bytes(S_box_inv[b] for b in state)

def xor_bytes(a, b):
    return bytes(x ^ y for x, y in zip(a, b))

def form_round_keys(master_key):
    k1 = master_key[:16]
    k2 = master_key[16:]
    keys = [k1, k2]

    for i in range(1, 9):
        for j in range(1, 9):
            idx = 8 * (i - 1) + j

            c_plain = bytes([0] * 15 + [idx])
            c = l_operation(c_plain)

            t = xor_bytes(k1, c)
            t = s_operation(t)
            t = l_operation(t)
            t = xor_bytes(t, k2)

            k1, k2 = t, k1

        keys.append(k1)
        keys.append(k2)

    return keys[:10]

def encrypt_block(block, round_keys):
    for i in range(9):
        block = xor_bytes(block, round_keys[i])
        block = s_operation(block)
        block = l_operation(block)
    block = xor_bytes(block, round_keys[9])

    return block

def decrypt_block(block, round_keys):
    block = xor_bytes(block, round_keys[9])

    for i in range(8, -1, -1):
        block = l_inv_operation(block)
        block = s_inv_operation(block)
        block = xor_bytes(block, round_keys[i])

    return block

def padding(data):
    pad_len = 16 - (len(data) % 16)

    return data + bytes([pad_len]) * pad_len

def delete_padding(data):
    pad_len = data[-1]

    if pad_len < 1 or pad_len > 16:
        raise ValueError("Неверный отступ")

    if data[-pad_len:] != bytes([pad_len]) * pad_len:
        raise ValueError("Неверный отступ")

    return data[:-pad_len]

def encrypt(data, master_key_128):
    master_key = master_key_128 * 2
    round_keys = form_round_keys(master_key)

    data = padding(data)
    out = bytearray()

    for i in range(0, len(data), 16):
        out += encrypt_block(data[i:i + 16], round_keys)

    return bytes(out)

def decrypt(data, master_key_128):
    master_key = master_key_128 * 2
    round_keys = form_round_keys(master_key)

    out = bytearray()

    for i in range(0, len(data), 16):
        out += decrypt_block(data[i:i + 16], round_keys)

    return delete_padding(bytes(out))

def main():
    text = input("Введите сообщение для шифрования: ")
    key = input("Введите 16-ти байтовый ключ: ").encode()

    while len(key) != 16:
        key = input("Длина ключа должна быть 16 байт, введите ключ повторно: ").encode()

    print("Открытый текст:", text)

    encrypted = encrypt(text.encode("utf-8"), key)
    print("Шифротекст (hex):", encrypted.hex())

    decrypted = decrypt(encrypted, key)
    print("Расшифрованный текст:", decrypted.decode("utf-8"))

if __name__ == "__main__":
    main()
